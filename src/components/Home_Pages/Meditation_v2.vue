<script>
export default {
  data() {
    return {
      songs: [
        {
          title: "Rainy Day",
          artist: "Pixabay",
          src: "https://cdn.pixabay.com/audio/2022/11/11/audio_84306ee149.mp3",
        },
        {
          title: "Haunted Day",
          artist: "Helix",
          src: "https://www.soundhelix.com/examples/mp3/SoundHelix-Song-2.mp3",
        },
        {
          title: "Melachony",
          artist: "Helix",
          src: "https://cdn.pixabay.com/audio/2022/11/11/audio_84306ee149.mp3",
        },
        {
          title: "Hype Meditation",
          artist: "Moondate",
          src: "https://www.soundhelix.com/examples/mp3/SoundHelix-Song-2.mp3",
        },
        ],
      currentSongIndex: 0,
      isPlaying: false,
      volume: 50,
      currentTime: 0,
      duration: 0,
      audio: new Audio(),
    };
  },
  computed: {
    currentSong() {
      return this.songs[this.currentSongIndex];
    },
  },
  methods: {
    togglePlayPause() {
      if (this.isPlaying) {
        this.audio.pause();
      } else {
        this.audio.src = this.currentSong.src;
        this.audio.volume = this.volume / 100;
        this.audio.play();
      }
      this.isPlaying = !this.isPlaying;
    },
    nextSong() {
      this.currentSongIndex = (this.currentSongIndex + 1) % this.songs.length;
      if (this.isPlaying) {
        this.audio.src = this.currentSong.src;
        this.audio.play();
      }
    },
    prevSong() {
      this.currentSongIndex =
        (this.currentSongIndex - 1 + this.songs.length) % this.songs.length;
      if (this.isPlaying) {
        this.audio.src = this.currentSong.src;
        this.audio.play();
      }
    },
    formatTime(seconds) {
      const minutes = Math.floor(seconds / 60);
      const secs = Math.floor(seconds % 60);
      return `${minutes}:${secs < 10 ? "0" : ""}${secs}`;
    },
    updateTime() {
      this.currentTime = this.audio.currentTime;
      this.duration = this.audio.duration;
    },
    seek(event) {
      const newTime = event.target.value;
      this.audio.currentTime = newTime;
      this.currentTime = newTime;
    },
  },
  watch: {
    volume(newVolume) {
      this.audio.volume = newVolume / 100;
    },
    currentTime(newTime) {
      this.audio.currentTime = newTime;
    },
  },
  mounted() {
    this.audio.addEventListener("ended", this.nextSong);
    this.audio.addEventListener("timeupdate", this.updateTime);
  },
  destroyed() {
    this.audio.removeEventListener("ended", this.nextSong);
    this.audio.removeEventListener("timeupdate", this.updateTime);
    this.audio.pause();
    this.audio = null;
  },
};
</script>

